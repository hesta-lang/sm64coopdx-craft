#!/usr/bin/env python3
"""Embed official Minecraft Java textures and block sounds into a Lua manifest."""
from __future__ import annotations

import argparse
import base64
import pathlib
import struct

REQUIRED_BLOCK_TEXTURES = (
    "textures/block/stone.png",
    "textures/block/dirt.png",
    "textures/block/grass_block_top.png",
    "textures/block/grass_block_side.png",
    "textures/block/oak_planks.png",
    "textures/block/cobblestone.png",
    "textures/block/glass.png",
    "textures/block/bricks.png",
    "textures/block/sand.png",
    "textures/block/bedrock.png",
)
HUD_TEXTURES = (
    "textures/gui/sprites/hud/hotbar.png",
    "textures/gui/sprites/hud/hotbar_selection.png",
    "textures/gui/sprites/hud/hotbar_offhand_left.png",
    "textures/gui/sprites/hud/hotbar_offhand_right.png",
    "textures/gui/sprites/hud/crosshair.png",
    "textures/gui/sprites/hud/armor_full.png",
    "textures/gui/sprites/hud/armor_half.png",
    "textures/gui/sprites/hud/armor_empty.png",
    "textures/gui/sprites/hud/food_full.png",
    "textures/gui/sprites/hud/food_half.png",
    "textures/gui/sprites/hud/food_empty.png",
    "textures/gui/sprites/hud/heart/full.png",
    "textures/gui/sprites/hud/heart/half.png",
    "textures/gui/sprites/hud/heart/container.png",
    "textures/gui/sprites/hud/experience_bar_background.png",
    "textures/gui/sprites/hud/experience_bar_progress.png",
)
BLOCK_ICON_FILES = tuple(
    f"textures/stevecraft/icons/{name}.png"
    for name in (
        "stone", "dirt", "grass_block", "oak_planks", "cobblestone",
        "glass", "bricks", "sand", "bedrock",
    )
)
SOUND_FILES = tuple(
    f"sounds/{material}_{action}.ogg"
    for material in ("stone", "dirt", "grass", "wood", "glass", "sand")
    for action in ("step", "place", "break")
)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--asset-root", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()

    root = args.asset_root
    required_missing = [name for name in REQUIRED_BLOCK_TEXTURES if not (root / name).is_file()]
    if required_missing:
        raise SystemExit("Missing required block textures: " + ", ".join(required_missing))

    resources: dict[str, str] = {}
    for relative in REQUIRED_BLOCK_TEXTURES + HUD_TEXTURES + BLOCK_ICON_FILES + SOUND_FILES:
        path = root / relative
        if not path.is_file():
            if relative in REQUIRED_BLOCK_TEXTURES:
                raise SystemExit(f"Required texture is missing: {relative}")
            print(f"Optional embedded resource missing: {relative}")
            continue
        data = path.read_bytes()
        if relative in REQUIRED_BLOCK_TEXTURES or relative in BLOCK_ICON_FILES:
            if len(data) < 24 or data[:8] != b"\x89PNG\r\n\x1a\n":
                raise SystemExit(f"Invalid PNG file: {relative}")
            width, height = struct.unpack(">II", data[16:24])
            expected = (32, 32) if relative in BLOCK_ICON_FILES else (16, 16)
            if (width, height) != expected:
                raise SystemExit(f"Expected a {expected[0]}x{expected[1]} PNG, got {width}x{height}: {relative}")
        if not data:
            raise SystemExit(f"Empty resource: {relative}")
        resources[relative] = base64.b64encode(data).decode("ascii")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as output:
        output.write("-- Generated by tools/stevecraft_assets/embed_block_textures.py; do not edit.\n")
        output.write("return {\n")
        for relative in sorted(resources):
            encoded = resources[relative]
            output.write(f'    ["{relative}"] = [[{encoded}]],\n')
        output.write("}\n")

    encoded_total = sum(len(value) for value in resources.values())
    print(
        f"Embedded {len(resources)} resources "
        f"({encoded_total} base64 characters) into {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
